<?php declare(strict_types=1);

namespace IiifSearch\View\Helper;

use Common\Stdlib\DirectoryManager;
use DOMDocument;
use DOMElement;
use Laminas\Log\Logger;
use Laminas\View\Helper\AbstractHelper;
use Omeka\Api\Representation\ItemRepresentation;
use Omeka\Api\Representation\AbstractResourceEntityRepresentation;
use IiifSearch\Stdlib\FileResource;
use IiifSearch\Stdlib\PagePairer;
use IiifSearch\Stdlib\PageSource;
use IiifSearch\Stdlib\PageSourceHintReader;
use IiifSearch\Stdlib\PairingResult;
use Omeka\Api\Representation\MediaRepresentation;

/**
 * Split a multipage ALTO XML into per-page standalone ALTO documents.
 *
 * Used to expose one seeAlso per canvas in a IIIF manifest and to feed
 * Mirador-textoverlay annotations that target a single canvas.
 */
class XmlAltoSplitter extends AbstractHelper
{
    protected Logger $logger;

    protected DirectoryManager $directoryManager;

    protected string $basePath;

    protected string $pairingMode;

    /**
     * @var array Alto resource by canvas index, by item id.
     */
    protected array $pairings = [];

    public function __construct(
        Logger $logger,
        DirectoryManager $directoryManager,
        string $basePath,
        string $pairingMode = PairingResult::METHOD_AUTO
    ) {
        $this->logger = $logger;
        $this->directoryManager = $directoryManager;
        $this->basePath = $basePath;
        $this->pairingMode = $pairingMode ?: PairingResult::METHOD_AUTO;
    }

    /**
     * Return the absolute path to the ALTO XML for the given page index. Tries
     * in order: a multipage ALTO resource extracted and cached; per-page ALTO
     * resources (media or digital object) by positional order; ALTO files
     * generated by the Extract OCR job under files/alto/.
     *
     * @return string|null Absolute path, or null if no source matches.
     */
    public function __invoke(ItemRepresentation $item, int $pageIndex): ?string
    {
        $altoMedia = $this->findMultipageAltoMedia($item);
        if ($altoMedia) {
            $resolved = $this->resolveFromMultipageFile(
                $this->basePath . '/original/' . $altoMedia->filename(),
                $item,
                $pageIndex
            );
            if ($resolved) {
                return $resolved;
            }
        }

        // Per-page ALTO resource (media or DigitalObject) at the requested
        // positional index among the item's file resources.
        $perPage = $this->findPerPageAltoPath($item, $pageIndex);
        if ($perPage) {
            return $perPage;
        }

        // ALTO files produced by ExtractOcr under files/alto/.
        $generated = $this->findGeneratedAltoPath($item, $pageIndex);
        if ($generated) {
            return $generated;
        }

        // Consolidated single-file output of the extract-as-file target,
        // possibly multipage: files/alto/{item_id}.alto.xml.
        $consolidated = $this->consolidatedPath($item);
        if ($consolidated) {
            return $this->resolveFromMultipageFile($consolidated, $item, $pageIndex);
        }

        return null;
    }

    /**
     * Path of the consolidated alto of the item (files/alto/{item_id}.alto.xml).
     */
    public function consolidatedPath(ItemRepresentation $item): ?string
    {
        $path = sprintf('%s/alto/%d.alto.xml', $this->basePath, $item->id());
        return is_readable($path) ? $path : null;
    }

    /**
     * Extract page $pageIndex from a multipage ALTO file and cache it under
     * files/iiif-search/{item_id}/alto-{n}.xml. Returns the cached path or null
     * on failure.
     */
    protected function resolveFromMultipageFile(string $sourcePath, ItemRepresentation $item, int $pageIndex): ?string
    {
        if (!is_readable($sourcePath)) {
            return null;
        }
        $cacheDir = sprintf('%s/iiif-search/%d', $this->basePath, $item->id());
        $cachePath = sprintf('%s/alto-%d.xml', $cacheDir, $pageIndex);
        if (file_exists($cachePath)
            && filemtime($cachePath) >= filemtime($sourcePath)
        ) {
            return $cachePath;
        }
        if (!$this->directoryManager->checkDestinationDir($cacheDir, true)) {
            return null;
        }
        // Mono-page file: serve it directly.
        if ($this->countPages($sourcePath) <= 1) {
            return $pageIndex === 0 ? $sourcePath : null;
        }
        $page = $this->extractPage($sourcePath, $item, $pageIndex);
        if (!$page || !@file_put_contents($cachePath, $page)) {
            return null;
        }
        return $cachePath;
    }

    /**
     * Whether the item carries any ALTO source the splitter can serve.
     */
    public function hasAnyAlto(ItemRepresentation $item): bool
    {
        if ($this->findMultipageAltoMedia($item)) {
            return true;
        }
        $itemFileResources = $this->getView()->plugin('itemFileResources');
        foreach ($itemFileResources($item) as $resource) {
            if ($resource->mediaType() === 'application/alto+xml') {
                return true;
            }
        }
        // Scan files/alto/ for any file matching this item: per-page
        // ({id}-page-NNN.alto.xml or {id}-*.alto.xml), or consolidated
        // ({id}.alto.xml) output of the extract-as-file target.
        $altoDir = $this->basePath . '/alto';
        if (is_dir($altoDir)) {
            $consolidated = sprintf('%s/%d.alto.xml', $altoDir, $item->id());
            if (is_readable($consolidated)) {
                return true;
            }
            $glob = @glob(sprintf('%s/%d-*.alto.xml', $altoDir, $item->id())) ?: [];
            if ($glob) {
                return true;
            }
        }
        return false;
    }

    /**
     * @return string|null Path of the per-page ALTO resource matching the index.
     */
    protected function findPerPageAltoPath(ItemRepresentation $item, int $pageIndex): ?string
    {
        $target = $this->findPerPageAltoResource($item, $pageIndex);
        if (!$target) {
            return null;
        }
        // The alto of a page may contain several pages, for example an export
        // of a whole range of pages, so extract the requested one.
        $path = $this->basePath . '/original/' . $target->filename();
        return $this->countPages($path) > 1
            ? $this->resolveFromMultipageFile($path, $item, $pageIndex)
            : $path;
    }

    /**
     * Return the resource carrying the OCR of a page, when it is an attached
     * file.
     *
     * Null means that the ALTO is generated (Extract OCR job or consolidated
     * file) and therefore not attached: the caller applies the access level of
     * the image of the page instead.
     */
    public function sourceResource(ItemRepresentation $item, int $pageIndex): ?AbstractResourceEntityRepresentation
    {
        $altoMedia = $this->findMultipageAltoMedia($item);
        if ($altoMedia) {
            $path = $this->basePath . '/original/' . $altoMedia->filename();
            if ($this->resolveFromMultipageFile($path, $item, $pageIndex)) {
                return $altoMedia;
            }
        }

        $target = $this->findPerPageAltoResource($item, $pageIndex);
        return $target ? $target->inner() : null;
    }

    /**
     * Find the per-page ALTO file resource at the given positional index.
     */
    protected function findPerPageAltoResource(ItemRepresentation $item, int $pageIndex): ?FileResource
    {
        $target = $this->pairAltos($item)[$pageIndex] ?? null;
        return $target && is_readable($this->basePath . '/original/' . $target->filename())
            ? $target
            : null;
    }

    /**
     * Pair the alto of each page with the canvases, like the search.
     *
     * The pairing uses the mode set in the config (by default, a cascade of
     * heuristics: METS, image hint of the alto, file name, number, etc.), so a
     * missing alto does not shift the next pages. The result is cached, because
     * the cascade reads all the altos.
     *
     * @return FileResource[] Alto resource by canvas index.
     */
    protected function pairAltos(ItemRepresentation $item): array
    {
        $itemId = (int) $item->id();
        if (isset($this->pairings[$itemId])) {
            return $this->pairings[$itemId];
        }

        $itemFileResources = $this->getView()->plugin('itemFileResources');
        $altos = [];
        foreach ($itemFileResources($item) as $resource) {
            if ($resource->mediaType() === 'application/alto+xml') {
                $altos[] = $resource;
            }
        }
        // The canvases are the images, like in the manifest and the search, so
        // the pdf and the text files attached to each page do not shift them.
        $canvases = $itemFileResources->images($item);
        if (count($altos) <= 1) {
            return $this->pairings[$itemId] = [];
        }

        $altosById = [];
        $signature = [$this->pairingMode];
        foreach ($altos as $alto) {
            $altosById[(int) $alto->id()] = $alto;
            $filepath = $this->basePath . '/original/' . $alto->filename();
            $signature[] = $alto->id() . ':' . $alto->filename() . ':' . (int) @filemtime($filepath);
        }
        foreach ($canvases as $canvas) {
            $signature[] = (int) $canvas->id();
        }
        $signature = md5(implode('|', $signature));

        $cacheDir = sprintf('%s/iiif-search/%d', $this->basePath, $itemId);
        $cachePath = $cacheDir . '/pairing.json';
        $cache = is_readable($cachePath)
            ? json_decode((string) file_get_contents($cachePath), true)
            : null;
        if (!is_array($cache) || ($cache['signature'] ?? null) !== $signature) {
            $cache = [
                'signature' => $signature,
                'altos' => $this->computePairing($item, $altos, $canvases),
            ];
            if ($this->directoryManager->checkDestinationDir($cacheDir, true)) {
                @file_put_contents($cachePath, json_encode($cache));
            }
        }

        $result = [];
        foreach ($cache['altos'] as $canvasIndex => $altoId) {
            if ($altoId && isset($altosById[$altoId])) {
                $result[(int) $canvasIndex] = $altosById[$altoId];
            }
        }
        return $this->pairings[$itemId] = $result;
    }

    /**
     * @param FileResource[] $altos
     * @param FileResource[] $canvases
     * @return array Alto id by canvas index.
     */
    protected function computePairing(ItemRepresentation $item, array $altos, array $canvases): array
    {
        $itemFileResources = $this->getView()->plugin('itemFileResources');
        $hintReader = new PageSourceHintReader();
        $sources = [];
        foreach ($altos as $index => $alto) {
            $filepath = $this->basePath . '/original/' . $alto->filename();
            $source = new PageSource($index + 1, $alto, $filepath, (string) $alto->source(), 'alto');
            $source->sourceImageFileName = $hintReader->readImageHint($filepath, 'alto');
            $sources[] = $source;
        }
        $pairer = new PagePairer($this->basePath, fn ($item) => $itemFileResources($item));
        $pairing = $pairer->pair($item, $sources, $this->pairingMode);

        $altoByCanvasId = [];
        foreach ($altos as $index => $alto) {
            $image = $pairing->resourceForPage($index + 1);
            if ($image) {
                $altoByCanvasId[(int) $image->id()] ??= (int) $alto->id();
            }
        }
        $result = [];
        foreach ($canvases as $canvasIndex => $canvas) {
            $result[$canvasIndex] = $altoByCanvasId[(int) $canvas->id()] ?? null;
        }
        return $result;
    }

    /**
     * @return string|null Path of the generated ALTO file for the page, if any.
     */
    protected function findGeneratedAltoPath(ItemRepresentation $item, int $pageIndex): ?string
    {
        $altoDir = $this->basePath . '/alto';
        if (!is_dir($altoDir)) {
            return null;
        }
        // Convention used by ExtractOcr::generateAltoFromImagesViaTesseract:
        // files/alto/{item_id}-page-{NNN}.alto.xml (1-based page number).
        $candidate = sprintf('%s/%d-page-%03d.alto.xml', $altoDir, $item->id(), $pageIndex + 1);
        if (is_readable($candidate)) {
            return $candidate;
        }
        // Fallback: take the (pageIndex)-th file in collection order.
        $glob = @glob(sprintf('%s/%d-*.alto.xml', $altoDir, $item->id())) ?: [];
        if (count($glob) > 1) {
            sort($glob, SORT_NATURAL);
            return $glob[$pageIndex] ?? null;
        }
        return null;
    }

    /**
     * Find the item resource (media or DigitalObject) that is an ALTO XML
     * containing more than one Page element.
     *
     * It is used only when it is the single ALTO of the item: the ALTO of each
     * page has priority, even if one of them contains several pages.
     */
    public function findMultipageAltoMedia(ItemRepresentation $item): ?AbstractResourceEntityRepresentation
    {
        $itemFileResources = $this->getView()->plugin('itemFileResources');
        $altos = [];
        foreach ($itemFileResources($item) as $resource) {
            if ($resource->mediaType() === 'application/alto+xml') {
                $altos[] = $resource;
            }
        }
        if (count($altos) !== 1) {
            return null;
        }
        $path = $this->basePath . '/original/' . $altos[0]->filename();
        return is_readable($path) && $this->countPages($path) > 1
            ? $altos[0]->inner()
            : null;
    }

    public function countPages(string $sourcePath): int
    {
        $reader = new \XMLReader();
        if (!@$reader->open($sourcePath)) {
            return 0;
        }
        $count = 0;
        while (@$reader->read()) {
            if ($reader->nodeType === \XMLReader::ELEMENT
                && $reader->localName === 'Page'
            ) {
                $count++;
            }
        }
        $reader->close();
        return $count;
    }

    /**
     * Extract a single <Page> wrapped in a minimal valid ALTO document.
     */
    protected function extractPage(string $sourcePath, ItemRepresentation $item, int $pageIndex): ?string
    {
        $dom = new DOMDocument();
        $dom->preserveWhiteSpace = false;
        if (!@$dom->load($sourcePath, LIBXML_NOBLANKS | LIBXML_NONET)) {
            return null;
        }

        $root = $dom->documentElement;
        if (!$root) {
            return null;
        }

        $layouts = $root->getElementsByTagName('Layout');
        if (!$layouts->length) {
            return null;
        }
        $layout = $layouts->item(0);

        $target = $this->matchPage($layout, $item, $pageIndex);
        if (!$target) {
            return null;
        }

        $out = new DOMDocument('1.0', 'UTF-8');
        $out->formatOutput = true;
        $altoNs = $root->namespaceURI ?: 'http://www.loc.gov/standards/alto/ns-v4#';
        $newRoot = $out->createElementNS($altoNs, $root->localName);
        $out->appendChild($newRoot);

        foreach ($root->childNodes as $child) {
            if ($child instanceof DOMElement && $child->localName === 'Description') {
                $newRoot->appendChild($out->importNode($child, true));
                break;
            }
        }

        $newLayout = $out->createElementNS($altoNs, 'Layout');
        $newRoot->appendChild($newLayout);
        $newLayout->appendChild($out->importNode($target, true));

        return $out->saveXML();
    }

    protected function matchPage(\DOMNode $layout, ItemRepresentation $item, int $pageIndex): ?DOMElement
    {
        $pages = [];
        foreach ($layout->childNodes as $node) {
            if ($node instanceof DOMElement && $node->localName === 'Page') {
                $pages[] = $node;
            }
        }
        if (!$pages) {
            return null;
        }

        // Auto-resolve: prefer PHYSICAL_IMG_NR when present, then match
        // Page/@ID against item file basenames, fall back to positional order.
        // The standard does not set the first number: it is 1 for most tools,
        // but 0 for some ones, like eScriptorium.
        $first = 1;
        $numbers = [];
        foreach ($pages as $page) {
            if (!$page->hasAttribute('PHYSICAL_IMG_NR')) {
                continue;
            }
            $number = (int) $page->getAttribute('PHYSICAL_IMG_NR');
            $numbers[$number] = true;
            if ($number === 0) {
                $first = 0;
            }
        }
        foreach ($pages as $page) {
            if ($page->hasAttribute('PHYSICAL_IMG_NR')
                && (int) $page->getAttribute('PHYSICAL_IMG_NR') - $first === $pageIndex
            ) {
                return $page;
            }
        }
        $itemFileResources = $this->getView()->plugin('itemFileResources');
        $resources = $itemFileResources($item);
        $target = $resources[$pageIndex] ?? null;
        if ($target) {
            $base = pathinfo($target->source() ?: $target->filename(), PATHINFO_FILENAME);
            foreach ($pages as $page) {
                $id = $page->getAttribute('ID');
                if ($id === $base || $id === 'Page_' . $base) {
                    return $page;
                }
            }
        }
        // When the numbering is reliable (all pages numbered, all distinct), a
        // missing number means that the page has no text, for example a page
        // without ocr in a consolidated file, so the positional order would
        // return the text of the next page.
        if (count($numbers) === count($pages)) {
            return null;
        }
        return $pages[$pageIndex] ?? null;
    }
}
